/**
 * block id -> a lazily-loaded component TYPE, for the props playground.
 *
 * ── WHY A SECOND MAP EXISTS ─────────────────────────────────────────────
 *
 * `blocks/registry.tsx` maps ids to *elements* — `<HeroSplit />`, already
 * constructed — and that is deliberate and load-bearing. Building elements
 * at module load is what makes their identity stable; looking a component
 * type out of a map and instantiating it inside a render is the pattern
 * `react-hooks/static-components` exists to catch, and a component whose
 * identity changes on every render remounts and drops its state. Every
 * preview in the grid, on the detail page and in the builder comes out of
 * that map and must keep coming out of it.
 *
 * A playground needs the opposite thing: a component type it can call with
 * props the reader is changing. `lib/blocks/props-table.ts` says so in its
 * header, and concluded that inverting the registry to get one would trade
 * a real correctness property for a set of sliders. That reasoning holds.
 * What it did not consider is a SECOND map, which is what this generates:
 *
 *   registry.tsx           elements, eagerly built — every preview, unchanged
 *   playground-registry.ts types, lazily imported — one panel, on demand
 *
 * Nothing reads both. The element map keeps its stable identities because
 * nothing about it changes; the playground gets types without anything else
 * having to give them up.
 *
 * ── WHY GENERATED AND NOT HAND-WRITTEN ──────────────────────────────────
 *
 * A hand-written second map is a second list of 250 imports that has to
 * agree with the first one, and nothing would report it when it stopped.
 * This derives from `generated-block-exports.json`, which is itself derived
 * from `registry.tsx` and verified against each block's own source — so the
 * two maps cannot name different symbols, and a block added to the registry
 * appears here on the next build without anyone remembering to add it.
 *
 * ── WHY EVERY ENTRY IS LAZY ─────────────────────────────────────────────
 *
 * `next/dynamic`, one chunk per block, none of them fetched until a reader
 * opens the panel. A static import map would put all 250 block sources into
 * the client graph of all 250 detail pages, which is precisely the weight
 * the element registry stays server-side to avoid — and these pages are on
 * a site whose catalog grids already ship about 4MB.
 *
 *     node scripts/build-block-playground.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = process.cwd()
const BLOCKS_DIR = join(ROOT, 'src', 'lib', 'blocks')
const EXPORTS = join(BLOCKS_DIR, 'generated-block-exports.json')
const OUT = join(BLOCKS_DIR, 'playground-registry.ts')

const { exports: entries } = JSON.parse(readFileSync(EXPORTS, 'utf8'))
const ids = Object.keys(entries).sort()

if (ids.length === 0) {
  throw new Error(
    'build-block-playground: generated-block-exports.json is empty — run build-block-exports first',
  )
}

const lines = ids.map((id) => {
  const symbol = entries[id]
  return `  '${id}': dynamic(() => import('./sources/${id}').then((m) => m.${symbol}), {\n    ssr: false,\n    loading: () => null,\n  }),`
})

const file = `'use client'

/* GENERATED by scripts/build-block-playground.mjs — do not edit.
 *
 * block id -> the component TYPE, lazily imported, for the props
 * playground on /block/[slug]. See the generator for why this map exists
 * alongside registry.tsx rather than replacing it: that one holds elements
 * and must keep holding elements, this one holds types and is read by
 * exactly one component.
 *
 * \`ssr: false\` because the panel only ever renders after a reader has
 * clicked to open it — there is no server pass worth paying for, and a
 * block that touches a browser API on mount would fail one.
 */

import dynamic from 'next/dynamic'
import type * as React from 'react'

/**
 * Props are \`Record<string, unknown>\` rather than each block's own
 * interface: the playground builds its values from the props table, which
 * is parsed out of source text and typed as strings. The component still
 * checks them at runtime the way it always did, and the panel only ever
 * sends props it read off that block's own signature.
 */
export const PLAYGROUND_BLOCKS: Record<
  string,
  React.ComponentType<Record<string, unknown>>
> = {
${lines.join('\n')}
}

/** The component type for one block, or undefined if it has no entry. */
export function getPlaygroundBlock(
  id: string,
): React.ComponentType<Record<string, unknown>> | undefined {
  return PLAYGROUND_BLOCKS[id]
}
`

writeFileSync(OUT, file)

console.log(`build-block-playground: wrote ${ids.length} lazy entries to ${OUT}`)
