/**
 * Animated icons — the icon browser crossed with the catalog's motion model.
 *
 * Preline ships 100 animated icons. Every set like it is a folder of 100
 * hand-made files, which has two consequences nobody mentions: the motion you
 * want is only available on the icons somebody already drew it for, and the
 * icon you need is only available with the motions somebody already thought
 * of. A 100-file set is not 100 choices, it is 100 *pairs*.
 *
 * This is the crossing instead. 136 icons from `/tools/icons` and twelve
 * motion families, emitted by one renderer, which makes every pair available
 * and makes the set's size a multiplication rather than a headcount.
 *
 * Three things follow from doing it as a crossing, and they are the reason
 * this is worth building rather than copying:
 *
 * 1. **The motion is applied per path, not to a box.** Rotating the whole
 *    `<svg>` is what a CSS one-liner does and it is why most "animated icon"
 *    demos look like a loading spinner wearing an icon. Lucide icons are two
 *    to six separate shapes, and the geometry arrives here as that list — so
 *    a bell can draw itself on stroke by stroke, in order, with a stagger.
 *    Four of the twelve families exist only because the parts are addressable.
 *
 * 2. **`prefers-reduced-motion` is not optional and not an afterthought.**
 *    Eight families are guarded by `reducedMotionGuard` from
 *    `keyframes-css.ts` — the same function the catalog's own effects are
 *    guarded by, called rather than reimplemented, so the rule here cannot
 *    drift from the rule there. The four dash families need more than that
 *    function can express, and the extra is explained where it is emitted.
 *
 * 3. **The keyframes come from the same model `/tools/keyframes` edits.**
 *    Nine families are an `Animation` (see `keyframes-css.ts`) and their CSS
 *    is *derived*; three are hand-written because the timeline model has no
 *    `stroke-dashoffset` and no `rotateY`, and they say so rather than being
 *    approximated into something subtly different. That split, and the reason
 *    for it, is lifted from `motion-presets.ts`, which made the same call.
 *
 * Pure string building over plain data, no DOM and no React — so it runs in
 * the route handler that serves a download, in the Node test runner, and in
 * the browser panel, from one implementation.
 *
 * Icon geometry is ISC-licensed from Lucide and regenerated by
 * `scripts/build-icon-nodes.mjs`. The notice travels with it.
 */

