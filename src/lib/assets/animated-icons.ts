/** One drawable element of an icon: a tag and its attributes. */
export type IconNode = [string, Record<string, string | number>]

export interface IconGeometry {
  /** The Lucide export name, as the icon browser lists it. */
  name: string
  /** Lucide's own file stem. Stable across renames of the export. */
  slug: string
  keywords: string
  nodes: IconNode[]
}

export const ICON_GEOMETRY: IconGeometry[] = generated.icons as IconGeometry[]
export const ICON_LICENSE = generated.license
export const LUCIDE_VERSION = generated.lucideVersion

export function iconBySlug(slug: string): IconGeometry | undefined {
  return ICON_GEOMETRY.find((i) => i.slug === slug)
}

/**
 * Lucide's own root attributes, restated.
 *
 * They are defaults inside the React component and therefore invisible in the
 * geometry, but an icon emitted without them is a black blob: `fill="none"`
 * is what keeps a stroked outline from filling, and the two `linecap` values
 * are most of what makes a Lucide icon look like one. Restating them is the
 * price of emitting files rather than elements.
 */
export const ICON_ROOT_ATTRS = {
  fill: 'none',
  stroke: 'currentColor',
  'stroke-linecap': 'round',
  'stroke-linejoin': 'round',
} as const

/* ============================================================
 *  Families
 * ============================================================ */

export type IconMotionId =
  | 'draw'
  | 'trace'
  | 'fade-stagger'
  | 'pop'
  | 'fade-in'
  | 'spin'
  | 'swing'
  | 'pulse'
  | 'bounce'
  | 'shake'
  | 'float'
  | 'flip'

export type IconMotionGroup = 'Enter' | 'Attention' | 'Loop'

export interface IconMotion {
  id: IconMotionId
  name: string
  group: IconMotionGroup
  /** What this one is for — the reason to pick it over the next one. */
  note: string
  /**
   * True when the animation is applied to each of the icon's shapes in turn
   * rather than to the icon as a whole. These are the families a folder of
   * pre-made files cannot offer, because they need the parts.
   */
  perPath: boolean
  /**
   * How the family uses `stroke-dasharray`, if at all.
   *
   * `draw` hides the stroke and reveals it; `march` leaves a gap travelling
   * along it forever. Both set static properties that the reduced-motion
   * guard then has to undo — see `guardFor`.
   */
  dash: 'draw' | 'march' | null
  /** Default duration in ms. The UI opens here. */
  duration: number
  /** Default per-shape stagger in ms. Meaningless when `perPath` is false. */
  stagger: number
  /**
   * The editable form. Present on everything the timeline model can express,
   * and when it is present the keyframes below are generated from it.
   */
  anim?: Animation
  /** Keyframes body. Only for the families the model cannot express. */
  frames?: string
  /** Easing, for the hand-written families. */
  easing?: string
  /** Loops forever. Only for the hand-written families. */
  forever?: boolean
  /**
   * Whether the animation should hold its last frame.
   *
   * True for anything that *arrives* somewhere — without it a delayed enter
   * animation shows its end state, waits, then jumps back to the start to
   * play, which reads as a flicker. False for attention motions, which are
   * supposed to end where they began.
   */
  holds: boolean
}

const ease = 'cubic-bezier(0.22, 1, 0.36, 1)'

/** An `Animation` from stops, with the fields every family here shares. */
function anim(
  stops: Parameters<typeof withIds>[0],
  over: Partial<Omit<Animation, 'stops'>> = {},
): Animation {
  return {
    duration: 600,
    delay: 0,
    easing: ease,
    iterations: 1,
    direction: 'normal',
    fill: 'none',
    ...over,
    stops: withIds(stops),
  }
}

